#!/usr/bin/env python3
"""Set the UI-only opportunities page password; run from the repository root."""
import getpass
import hashlib
import secrets
from pathlib import Path

password = getpass.getpass("New opportunities password: ")
confirm = getpass.getpass("Confirm password: ")
if not password or password != confirm:
    raise SystemExit("Passwords must be nonempty and match.")
salt = secrets.token_hex(16)
digest = hashlib.sha256((salt + password).encode("utf-8")).hexdigest()
path = Path(__file__).resolve().parent.parent / "_data" / "opportunities_gate.yml"
path.write_text(
    '# UI-only gate: generated by scripts/set_opportunities_password.py.\n'
    '# The protected page and its data remain public in the repository.\n'
    f'salt: "{salt}"\npassword_hash: "{digest}"\n',
    encoding="utf-8",
)
print("Password updated. Commit and push _data/opportunities_gate.yml to publish.")
